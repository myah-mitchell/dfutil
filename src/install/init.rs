//! Shell init scripts generated once at install time (`starship init zsh`,
//! `zoxide init nushell`) instead of on every new shell.
//!
//! Each tool's output goes to `<init_dir>/<tool>.<ext>`, and one aggregate
//! `<init_dir>/init.<ext>` per shell sources them all, so a shell rc file
//! needs a single line.

use crate::config::ToolDef;
use crate::paths::Paths;
use anyhow::{Context, Result, bail};
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::process::Command;

/// File extension for a shell's init scripts.
pub fn extension(shell: &str) -> Result<&'static str> {
    Ok(match shell {
        "zsh" => "zsh",
        "bash" => "bash",
        "nushell" | "nu" => "nu",
        other => bail!("unsupported shell `{other}` (expected zsh, bash, or nushell)"),
    })
}

/// Shells dfapp can generate init scripts for.
pub const SHELLS: [&str; 3] = ["zsh", "bash", "nushell"];

/// Path of one tool's generated script.
pub fn tool_script(paths: &Paths, tool: &str, shell: &str) -> Result<PathBuf> {
    Ok(paths.init_dir.join(format!("{tool}.{}", extension(shell)?)))
}

/// Generates `tool`'s init scripts for each of `shells` it defines. Returns
/// the files written.
pub fn generate(
    paths: &Paths,
    name: &str,
    tool: &ToolDef,
    shells: &BTreeSet<String>,
) -> Result<Vec<PathBuf>> {
    let mut written = Vec::new();
    for (shell, command) in &tool.init {
        if !shells.contains(shell) {
            continue;
        }
        let output = Command::new("sh")
            .arg("-c")
            .arg(command)
            .env("PATH", super::path_with_bin(paths))
            .output()
            .with_context(|| format!("{name}: running init command for {shell}"))?;
        if !output.status.success() {
            bail!(
                "{name}: init command `{command}` failed: {}",
                String::from_utf8_lossy(&output.stderr).trim()
            );
        }
        let path = tool_script(paths, name, shell)?;
        crate::util::write_atomic(&path, &output.stdout)?;
        written.push(path);
    }
    Ok(written)
}

/// Deletes a tool's generated scripts.
pub fn remove(paths: &Paths, name: &str) {
    for shell in SHELLS {
        if let Ok(path) = tool_script(paths, name, shell) {
            std::fs::remove_file(path).ok();
        }
    }
}

/// Rewrites the aggregate `init.<ext>` for every shell so it sources the
/// scripts of `installed` tools that have one, in name order. Always writes
/// the files, even empty, so an rc file can source them unconditionally.
pub fn write_aggregates(paths: &Paths, installed: &BTreeMap<String, &ToolDef>) -> Result<()> {
    std::fs::create_dir_all(&paths.init_dir)
        .with_context(|| format!("creating {}", paths.init_dir.display()))?;
    for shell in SHELLS {
        let ext = extension(shell)?;
        let mut text = String::from("# Generated by dfapp; edits are overwritten.\n");
        for name in installed.keys() {
            let script = tool_script(paths, name, shell)?;
            if script.exists() {
                text.push_str(&source_line(shell, &script));
            }
        }
        crate::util::write_atomic(&paths.init_dir.join(format!("init.{ext}")), text.as_bytes())?;
    }
    Ok(())
}

fn source_line(shell: &str, script: &Path) -> String {
    let quoted = script.display().to_string().replace('\'', "'\\''");
    match shell {
        // Nushell's `source` is resolved at parse time and needs a literal path.
        "nushell" => format!(
            "source \"{}\"\n",
            script.display().to_string().replace('"', "\\\"")
        ),
        _ => format!("source '{quoted}'\n"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::paths::Scope;

    #[test]
    fn generates_per_tool_scripts_and_aggregates() {
        let home = tempfile::tempdir().unwrap();
        let paths = Paths::for_home(home.path(), Scope::User);
        let tool: ToolDef = toml::from_str(
            "repo = \"a/b\"\ninit = { zsh = \"echo 'eval zsh'\", nushell = \"echo nu-init\" }",
        )
        .unwrap();
        let shells: BTreeSet<String> = ["zsh".to_string()].into();
        let written = generate(&paths, "starship", &tool, &shells).unwrap();
        assert_eq!(written.len(), 1);
        assert_eq!(std::fs::read_to_string(&written[0]).unwrap(), "eval zsh\n");

        let installed: BTreeMap<String, &ToolDef> = [("starship".to_string(), &tool)].into();
        write_aggregates(&paths, &installed).unwrap();
        let zsh = std::fs::read_to_string(paths.init_dir.join("init.zsh")).unwrap();
        assert!(zsh.contains("starship.zsh"));
        let nu = std::fs::read_to_string(paths.init_dir.join("init.nu")).unwrap();
        assert!(
            !nu.contains("source"),
            "nushell wasn't selected, so nothing is sourced"
        );

        remove(&paths, "starship");
        assert!(!written[0].exists());
    }

    #[test]
    fn failing_init_commands_report_stderr() {
        let home = tempfile::tempdir().unwrap();
        let paths = Paths::for_home(home.path(), Scope::User);
        let tool: ToolDef =
            toml::from_str("repo = \"a/b\"\ninit = { zsh = \"echo boom >&2; exit 3\" }").unwrap();
        let shells: BTreeSet<String> = ["zsh".to_string()].into();
        let error = generate(&paths, "x", &tool, &shells)
            .unwrap_err()
            .to_string();
        assert!(error.contains("boom"));
    }
}
